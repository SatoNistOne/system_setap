#!/bin/bash
# Runs INSIDE arch-chroot after archinstall (called by install.sh).
# Turns the bare Arch install into the golden base (decisions §2, §4):
#   CachyOS repo + linux-cachyos (+ Nvidia modules), systemd initramfs with
#   sd-encrypt + Plymouth, Limine with UKIs, snapper + snap-pac +
#   limine-snapper-sync, zram, hibernation swap file, nested subvolumes.
# Greetd autologin is NOT enabled here: first boot is a console login, then
# phase 2 (chezmoi) installs Niri and turns autologin on (decisions §1).
#
# Input: install.env next to this script (written by install.sh).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(dirname "$HERE")"
GOLDEN_LOG=/var/log/golden-install.log
# shellcheck source=install/lib.sh
source "$HERE/lib.sh"
# shellcheck source=/dev/null
source "$HERE/install.env"
: "${USERNAME:?}" "${USE_LUKS:?}" "${FS_UUID:?}" "${IS_LAPTOP:?}" "${HAS_NVIDIA:?}"
: "${DISPLAY_NAME:=}" "${LUKS_UUID:=}" "${SWAP_OFFSET:=}" "${IS_HYBRID_GPU:=false}"

CACHYOS_KEY=F3B607488DB35A47
USER_HOME="/home/$USERNAME"

# Install a repo file to its system path (system/etc/x → /etc/x).
put() {  # put system/relative/path [mode]
    install -Dm"${2:-644}" "$REPO_DIR/$1" "/${1#system/}"
}

pac() { pacman -S --needed --noconfirm "$@" 2>&1 | tee -a "$GOLDEN_LOG"; return "${PIPESTATUS[0]}"; }

# --- 1. Static system files (also maintained later by chezmoi run_onchange) --
step "System files"
put system/etc/mkinitcpio.conf.d/golden.conf
put system/etc/snapper/configs/root 640
put system/etc/snapper/configs/home 640
put system/etc/conf.d/snapper
put system/etc/snap-pac.ini
put system/etc/systemd/zram-generator.conf
put system/etc/systemd/system/snapper-timeline.timer.d/daily.conf
for f in "$REPO_DIR"/system/usr/share/plymouth/themes/golden/*; do
    put "system/usr/share/plymouth/themes/golden/$(basename "$f")"
done

# Nvidia-only desktop: load the driver in the initramfs so Plymouth has a
# display (early KMS). Hybrid laptops keep it out: the iGPU draws the
# prompt and the dGPU may sleep (RTD3). Generated by hardware → not in system/.
if $HAS_NVIDIA && ! $IS_HYBRID_GPU; then
    printf '%s\n' '# golden: early KMS for Nvidia-only machines (written by install.sh).' \
        'MODULES+=(nvidia nvidia_modeset nvidia_uvm nvidia_drm)' \
        > /etc/mkinitcpio.conf.d/nvidia.conf
fi

# --- 2. Kernel command line → /etc/default/limine ---------------------------
step "Kernel command line"
if $USE_LUKS; then
    CMDLINE="rd.luks.name=$LUKS_UUID=root root=/dev/mapper/root rootflags=subvol=@ rw"
else
    CMDLINE="root=UUID=$FS_UUID rootflags=subvol=@ rw"
fi
if $IS_LAPTOP && [ -n "$SWAP_OFFSET" ]; then
    # Hibernation into the swap file; systemd-initramfs resumes by itself.
    CMDLINE+=" resume=UUID=$FS_UUID resume_offset=$SWAP_OFFSET"
fi
sed "s|@@CMDLINE@@|$CMDLINE|" "$HERE/files/default-limine.in" > /etc/default/limine
info "$CMDLINE"
# Header for limine.conf; limine-update appends the entries.
install -Dm644 "$HERE/files/limine.conf" /boot/limine.conf

# --- 3. CachyOS repo (only [cachyos], decisions §2) ------------------------
step "CachyOS repository"
if ! grep -q '^\[cachyos\]' /etc/pacman.conf; then
    received=false
    for ks in hkps://keyserver.ubuntu.com hkps://keys.openpgp.org; do
        if pacman-key --recv-keys "$CACHYOS_KEY" --keyserver "$ks" >>"$GOLDEN_LOG" 2>&1; then
            received=true; break
        fi
    done
    $received || die "Could not fetch the CachyOS signing key."
    pacman-key --lsign-key "$CACHYOS_KEY" >>"$GOLDEN_LOG" 2>&1
    # [cachyos] above [core] (as CachyOS documents). First with a direct
    # Server line, then switched to the mirrorlist package.
    awk '/^\[core\]/ && !done {
            print "[cachyos]"
            print "Server = https://mirror.cachyos.org/repo/$arch/$repo"
            print ""
            done = 1
         } { print }' /etc/pacman.conf > /etc/pacman.conf.new
    mv /etc/pacman.conf.new /etc/pacman.conf
    pacman -Sy --noconfirm >>"$GOLDEN_LOG" 2>&1
    pac cachyos-keyring cachyos-mirrorlist >/dev/null
    # shellcheck disable=SC2016  # $arch/$repo are literal pacman variables
    sed -i 's|^Server = https://mirror.cachyos.org/repo/\$arch/\$repo$|Include = /etc/pacman.d/cachyos-mirrorlist|' /etc/pacman.conf
    pacman -Sy --noconfirm >>"$GOLDEN_LOG" 2>&1
fi
grep -A1 '^\[cachyos\]' /etc/pacman.conf | tee -a "$GOLDEN_LOG"

# --- 4. Kernel, Limine tooling, Nvidia modules ------------------------------
step "Kernel and boot tooling"
mapfile -t pkgs < <(pkglist "$REPO_DIR/packages/base/cachyos.txt")
pac "${pkgs[@]}" >/dev/null || die "Installing CachyOS packages failed (see $GOLDEN_LOG)."

if $HAS_NVIDIA; then
    step "Nvidia kernel modules"
    mapfile -t pkgs < <(pkglist "$REPO_DIR/packages/base/hw-nvidia.txt")
    if ! pac "${pkgs[@]}" >/dev/null; then
        # nvidia-open-lts (Arch) may want another nvidia-utils version than
        # [cachyos] ships. Fallback: DKMS module built for linux-lts only
        # (no linux-cachyos-headers → DKMS leaves the CachyOS kernel alone).
        warn "nvidia-open-lts failed — falling back to nvidia-open-dkms for linux-lts."
        pac linux-cachyos-nvidia-open nvidia-utils nvidia-open-dkms linux-lts-headers >/dev/null \
            || warn "Nvidia fallback failed too — linux-lts will boot without Nvidia (nouveau)."
    fi
fi

# --- 5. Limine on the ESP ---------------------------------------------------
step "Limine bootloader"
install -Dm644 /usr/share/limine/BOOTX64.EFI /boot/EFI/limine/BOOTX64.EFI
# Removable-media path as well: some firmware ignores NVRAM entries.
install -Dm644 /usr/share/limine/BOOTX64.EFI /boot/EFI/BOOT/BOOTX64.EFI
# Keep the EFI binary current on limine updates — unless limine-entry-tool
# already ships a deploy hook.
if ! ls /usr/share/libalpm/hooks/*limine*deploy* >/dev/null 2>&1; then
    install -d /etc/pacman.d/hooks
    printf '%s\n' \
        '[Trigger]' 'Operation = Install' 'Operation = Upgrade' 'Type = Package' 'Target = limine' \
        '' '[Action]' 'Description = Deploying Limine EFI to the ESP...' 'When = PostTransaction' \
        'Exec = /usr/bin/sh -c "install -Dm644 /usr/share/limine/BOOTX64.EFI /boot/EFI/limine/BOOTX64.EFI && install -Dm644 /usr/share/limine/BOOTX64.EFI /boot/EFI/BOOT/BOOTX64.EFI"' \
        > /etc/pacman.d/hooks/99-golden-limine-deploy.hook
fi
# (The NVRAM boot entry is created by install.sh outside the chroot.)

# --- 6. Plymouth logo from the display name ---------------------------------
step "Plymouth theme"
banner_name="$DISPLAY_NAME"
[ -n "$banner_name" ] || banner_name="$USERNAME"
# figlet fonts are Latin-only: a non-Latin name falls back to the login.
LC_ALL=C grep -q '[^ -~]' <<< "$banner_name" && banner_name="$USERNAME"
font="$(fc-match -f '%{file}' 'JetBrainsMono Nerd Font:style=Bold' 2>/dev/null || true)"
banner="$(figlet -w 200 "$banner_name")"
magick -background none -fill white ${font:+-font "$font"} -pointsize 16 \
    label:"$banner" /usr/share/plymouth/themes/golden/logo.png \
    || warn "Could not render the Plymouth logo — theme will show no logo."
plymouth-set-default-theme golden

# --- 7. UKIs + boot menu ----------------------------------------------------
step "Building UKIs and the Limine menu"
limine-update 2>&1 | tee -a "$GOLDEN_LOG" || die "limine-update failed (see $GOLDEN_LOG)."
grep -q 'linux-cachyos' /boot/limine.conf || die "No linux-cachyos entry in /boot/limine.conf."

# --- 8. Snapshots -----------------------------------------------------------
step "Snapshots"
chmod 750 /.snapshots /home/.snapshots
systemctl enable snapper-cleanup.timer snapper-timeline.timer limine-snapper-sync.service \
    >>"$GOLDEN_LOG" 2>&1
# snap-pac last: from now on every pacman transaction is snapshotted.
mapfile -t pkgs < <(pkglist "$REPO_DIR/packages/base/late.txt")
pac "${pkgs[@]}" >/dev/null || die "Installing snap-pac failed."

# --- 9. Swap -----------------------------------------------------------------
if $IS_LAPTOP && [ -f /swap/swapfile ] && ! grep -q '^/swap/swapfile' /etc/fstab; then
    printf '%s\n' '/swap/swapfile none swap defaults,pri=10 0 0' >> /etc/fstab
fi

# --- 10. User ---------------------------------------------------------------
step "User $USERNAME"
if [ -n "$DISPLAY_NAME" ]; then
    usermod -c "$DISPLAY_NAME" "$USERNAME"
fi
# Nested subvolumes stay out of /home snapshots (decisions §4).
for d in "$USER_HOME/.cache" "$USER_HOME/.local/share/Steam"; do
    if [ ! -e "$d" ]; then
        install -d -o "$USERNAME" -g "$USERNAME" "$(dirname "$d")"
        btrfs subvolume create "$d" >>"$GOLDEN_LOG"
        chown "$USERNAME:$USERNAME" "$d"
    fi
done
chown "$USERNAME:$USERNAME" "$USER_HOME/.local" "$USER_HOME/.local/share"

# Phase 2 hint on the first console login; phase 2 clears /etc/motd.
printf '%s\n' '' \
    '  Golden setup — phase 2:' \
    '    chezmoi init --apply SatoNistOne/system_setap' \
    '' > /etc/motd

# gpg-agent/dirmngr started by pacman-key would keep /mnt busy for umount.
gpgconf --homedir /etc/pacman.d/gnupg --kill all 2>/dev/null || true

step "Base system ready"
